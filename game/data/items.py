def _mat_type(name: str) -> str:
    """材料类型（按名字关键词；无命中 → 杂物）"""
    for _t, _kws in _MAT_TYPE_RULES:
        if any(_k in name for _k in _kws):
            return _t
    return _MAT_TYPE_FALLBACK


def _mat_quality(price: int) -> str:
    """材料品质（全服通用白绿蓝紫橙，按价格分档）"""
    if price <= 12:
        return "white"
    if price <= 30:
        return "green"
    if price <= 60:
        return "blue"
    if price <= 120:
        return "purple"
    return "orange"


