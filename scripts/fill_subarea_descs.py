def main():
    with open(SUBAREAS_PATH, encoding="utf-8") as f:
        lines = f.readlines()

    cur_id = None
    replaced = 0
    missing = []
    for i, line in enumerate(lines):
        m = re.search(r'"id"\s*:\s*"([^"]+)"', line)
        if m:
            cur_id = m.group(1)
            continue
        m = re.search(r'"desc"\s*:\s*"([^"]*)"', line)
        if m and cur_id in DESCS:
            old = m.group(1)
            new = DESCS[cur_id]
            lines[i] = line.replace(f'"{old}"', f'"{new}"', 1)
            replaced += 1
            cur_id = None  # 每个 id 只替换紧跟的 desc

    for sa_id in DESCS:
        if not any(f'"id": "{sa_id}"' in l for l in lines):
            missing.append(sa_id)

    print(f"替换 desc: {replaced} / {len(DESCS)}")
    if missing:
        print(f"⚠️ 找不到的子区域 id: {missing}")

    with open(SUBAREAS_PATH, "w", encoding="utf-8", newline="") as f:
        f.writelines(lines)
    print("已写回 subareas.py")


if __name__ == "__main__":
    main()
