# 名字替换：注意 "旅店"/"码头"/"补给站"/"营地口"/"集市" 多次出现，必须按 id 锚点精确定位
# 策略：按 "id": "xxx",\n 附近的名字行替换
import re

def rename_by_id(src, sa_id, new_name, old_desc, new_desc):
    # 找该子区域块
    pattern = re.compile(
        r'(\{\s*"id": "' + re.escape(sa_id) + r'")(.*?)(\})',
        re.S
    )
    m = pattern.search(src)
    if not m:
        print(f"  !! {sa_id} 未找到")
        return src
    block = m.group(0)
    new_block = block
    # 替换 name 行
    nb = re.sub(r'("name": ")[^"]*(")', lambda mm: mm.group(1) + new_name + mm.group(2), new_block, count=1)
    if nb == new_block:
        print(f"  !! {sa_id} name 替换失败")
        return src
    new_block = nb
    # 替换 desc（如果 desc 片段匹配）
    if old_desc and old_desc in new_block:
        new_block = new_block.replace(old_desc, new_desc)
    else:
        print(f"  ~ {sa_id} desc 片段未匹配(跳过): {old_desc[:20]}")
    return src.replace(block, new_block)

